import { chromium } from 'playwright'
import { mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const shots = join(root, 'screenshots')
await mkdir(shots, { recursive: true })
// 浏览器路径可用环境变量 BROWSER_PATH 覆盖；未指定时不传 executablePath，交给 playwright 自动解析
const launchOptions = { headless: true }
if (process.env.BROWSER_PATH) launchOptions.executablePath = process.env.BROWSER_PATH
const browser = await chromium.launch(launchOptions)
for (const viewport of [{ width: 1440, height: 900, name: 'desktop' }, { width: 768, height: 1024, name: 'tablet' }, { width: 390, height: 844, name: 'mobile' }]) {
  const page = await browser.newPage({ viewport })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://127.0.0.1:5173', { waitUntil: 'networkidle' })
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)) throw new Error(`${viewport.name}: horizontal overflow`)
  const nav = await page.locator('.main-nav').boundingBox()
  const content = await page.locator('.page-bar').boundingBox()
  if (nav.y + nav.height > content.y) throw new Error(`${viewport.name}: navigation overlaps content`)
  await page.screenshot({ path: join(shots, `${viewport.name}.png`), fullPage: true })
  if (await page.locator('.leaflet-pane').count() === 0) throw new Error(`${viewport.name}: map missing`)
  if (await page.locator('.meeting-pin').count() !== 0) throw new Error(`${viewport.name}: meeting appeared too early`)
  await page.getByRole('button', { name: '下一段' }).click()
  if (await page.locator('.meeting-pin').count() === 0) throw new Error(`${viewport.name}: meeting not rendered`)
  for (let i = 1; i < 6; i++) await page.getByRole('button', { name: '下一段' }).click()
  if (!(await page.getByText('已完成').count())) throw new Error(`${viewport.name}: completion missing`)
  await page.screenshot({ path: join(shots, `${viewport.name}-complete.png`), fullPage: true })
  await page.getByRole('button', { name: '查看回放' }).click()
  if (!(await page.getByText('任务时间轴').count())) throw new Error(`${viewport.name}: replay missing`)
  await page.getByRole('button', { name: '退出回放' }).click()
  await page.getByRole('link', { name: '调度台' }).click()
  await page.screenshot({ path: join(shots, `${viewport.name}-console.png`), fullPage: true })
  await page.getByRole('link', { name: '船员端' }).click()
  await page.getByRole('button', { name: '提交订单' }).click()
  if (!(await page.getByText(/加入本地演示/).count())) throw new Error(`${viewport.name}: crew order missing`)
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)) throw new Error(`${viewport.name}: crew overflow`)
  await page.screenshot({ path: join(shots, `${viewport.name}-crew.png`), fullPage: true })
  if (errors.length) throw new Error(`${viewport.name}: ${errors.join('; ')}`)
  console.log(`${viewport.name}: map, meeting, six scenes, replay, crew order, no overflow or page errors`)
  await page.close()
}
const live = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const liveErrors = []
live.on('pageerror', e => liveErrors.push(e.message))
await live.goto('http://127.0.0.1:5173', { waitUntil: 'networkidle' })
await live.getByRole('button', { name: '实时服务' }).click()
await live.getByText('WebSocket 已连接').waitFor()
await live.getByRole('button', { name: '服务复位' }).click()
await live.getByRole('button', { name: '服务下一段' }).click()
await live.getByText('已派发', { exact: true }).first().waitFor()
if (await live.locator('.meeting-pin').count() === 0) throw new Error('live: WebSocket meeting frame missing')
await live.getByRole('link', { name: '船员端' }).click()
await live.getByRole('button', { name: '提交订单' }).click()
const receipt = live.getByText(/由演示服务接收/)
await receipt.waitFor()
const orderId = (await receipt.textContent()).match(/DEMO-\d+/)?.[0]
if (!orderId) throw new Error('live: new order ID missing')
await live.getByRole('link', { name: '态势大屏' }).click()
await live.getByRole('button', { name: '服务下一段' }).click()
await live.getByText(orderId).first().waitFor()
const orderResponse = await live.evaluate(async () => (await fetch('/api/orders')).json())
if (orderResponse.orders.length !== 1 || orderResponse.orders[0].orderId !== orderId || orderResponse.orders[0].orderStatus !== '已派发') throw new Error('live: order ID changed during scenario')
await live.getByRole('button', { name: '查看回放' }).click()
const history = await live.evaluate(async id => (await (await fetch(`/api/replay/${id}`)).json()).frames, orderId)
if (history.length < 4 || history.some(frame => frame.data.orderId && frame.data.orderId !== orderId)) throw new Error('live: replay history is inconsistent')
await live.getByRole('button', { name: '退出回放' }).click()
await live.getByText(orderId).first().waitFor()
await live.getByText('WebSocket 已连接').waitFor()
await live.locator('.meeting-pin').waitFor()
if (!(await live.locator('.ship-pin').count())) throw new Error('live: map did not restore after replay')
const storeCheck = await live.evaluate(async () => {
  const { createPinia } = await import('/node_modules/.vite/deps/pinia.js')
  const { useOrderStore } = await import('/src/stores/index.js')
  const store = useOrderStore(createPinia())
  const base = { orderId: 'CHECK', orderStatus: '待受理', eventTs: 1, stateVersion: 1 }
  store.apply(base)
  store.apply({ ...base, orderStatus: '已派发', stateVersion: 0 })
  store.apply({ ...base, eventTs: 2, stateVersion: 2 })
  return { status: store.byId.CHECK.orderStatus, count: store.timeline.CHECK.length }
})
if (storeCheck.status !== '待受理' || storeCheck.count !== 1) throw new Error('live: state version or timeline deduplication failed')
if (liveErrors.length) throw new Error(`live: ${liveErrors.join('; ')}`)
await live.screenshot({ path: join(shots, 'live.png'), fullPage: true })
console.log('live: WebSocket, reset, new order, coherent six-step ID, replay history, store version checks')
await live.close()
await browser.close()
